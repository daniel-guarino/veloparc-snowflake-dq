-- Functional roles, all managed by VLP_DEPLOYER.
CREATE ROLE IF NOT EXISTS VLP_LOADER COMMENT = 'Uploads to the landing stages, loads bronze';
CREATE ROLE IF NOT EXISTS VLP_TRANSFORMER COMMENT = 'dbt: reads bronze, writes silver, gold, dq';
CREATE ROLE IF NOT EXISTS VLP_READER COMMENT = 'Reads gold and dq';
CREATE ROLE IF NOT EXISTS VLP_CONNECTOR COMMENT = 'Aiven Snowflake sink connector';
GRANT ROLE VLP_LOADER, VLP_TRANSFORMER, VLP_READER, VLP_CONNECTOR TO ROLE VLP_DEPLOYER;

GRANT USAGE ON DATABASE VLP_DP TO ROLE VLP_LOADER;
GRANT USAGE ON DATABASE VLP_DP TO ROLE VLP_TRANSFORMER;
GRANT USAGE ON DATABASE VLP_DP TO ROLE VLP_READER;
GRANT USAGE ON DATABASE VLP_DP TO ROLE VLP_CONNECTOR;

-- Loader: landing stages and bronze.
GRANT USAGE ON SCHEMA VLP_DP.BRONZE TO ROLE VLP_LOADER;
GRANT READ, WRITE ON STAGE VLP_DP.BRONZE.LANDING TO ROLE VLP_LOADER;
GRANT READ, WRITE ON STAGE VLP_DP.BRONZE.GENERATOR TO ROLE VLP_LOADER;
GRANT USAGE ON FILE FORMAT VLP_DP.BRONZE.FF_LANDING_JSONL TO ROLE VLP_LOADER;
GRANT USAGE ON WAREHOUSE WH_LOAD TO ROLE VLP_LOADER;

-- Transformer (dbt) and reader.
GRANT USAGE ON SCHEMA VLP_DP.BRONZE TO ROLE VLP_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA VLP_DP.SILVER TO ROLE VLP_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA VLP_DP.GOLD TO ROLE VLP_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA VLP_DP.DQ TO ROLE VLP_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA VLP_DP.REF TO ROLE VLP_TRANSFORMER;
GRANT USAGE ON WAREHOUSE WH_TRANSFORM TO ROLE VLP_TRANSFORMER;
GRANT USAGE ON SCHEMA VLP_DP.GOLD TO ROLE VLP_READER;
GRANT USAGE ON SCHEMA VLP_DP.DQ TO ROLE VLP_READER;
GRANT USAGE ON WAREHOUSE WH_ANALYTICS TO ROLE VLP_READER;

-- Connector: creates and writes its own tables in BRONZE (Snowpipe Streaming, serverless).
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE PIPE ON SCHEMA VLP_DP.BRONZE TO ROLE VLP_CONNECTOR;

-- Service user for the connector. Its RSA public key is set by the connector workflow (Phase 3c), which also
-- creates the connector with the private key: the key is never stored.
CREATE USER IF NOT EXISTS SVC_AIVEN_CONNECTOR
  TYPE = SERVICE DEFAULT_ROLE = VLP_CONNECTOR
  COMMENT = 'Aiven Snowflake sink connector (key pair set by the connector workflow)';
GRANT ROLE VLP_CONNECTOR TO USER SVC_AIVEN_CONNECTOR;
