-- Reference tables and generator manifests (ADR 0004, decision 8), loaded by `veloparc-gen bronze-load` from
-- @BRONZE.GENERATOR: reference/<TABLE>/<TABLE>.csv (replaced on each load) and runs/<run_id>/*.json[l]
-- (appended; COPY skips files already loaded).

CREATE FILE FORMAT IF NOT EXISTS VLP_DP.BRONZE.FF_REFERENCE_CSV
  TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"' COMPRESSION = AUTO
  COMMENT = 'Generator reference tables: CSV with a header row';

CREATE FILE FORMAT IF NOT EXISTS VLP_DP.BRONZE.FF_GENERATOR_JSON
  TYPE = JSON COMPRESSION = AUTO
  COMMENT = 'Generator manifests: one JSON document (run_manifest.json) or JSON lines (*.jsonl), uncompressed';

-- REF: dbt reads these as sources (Phase 7).
CREATE TABLE IF NOT EXISTS VLP_DP.REF.FX_RATE_DAILY (
    RATE_DATE DATE,
    CURRENCY VARCHAR,
    RATE_TO_EUR NUMBER(18,6) COMMENT 'Units of EUR per unit of CURRENCY',
    _LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
) COMMENT = 'Daily FX rates to EUR (generator reference table)';

CREATE TABLE IF NOT EXISTS VLP_DP.REF.POSTAL_ZONE (
    COUNTRY_CODE VARCHAR,
    POSTAL_PREFIX VARCHAR,
    ZONE_CODE VARCHAR,
    _LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
) COMMENT = 'Postal-code prefix to delivery zone (generator reference table)';

CREATE TABLE IF NOT EXISTS VLP_DP.REF.COUNTRY_ALIAS (
    ALIAS_NORM VARCHAR COMMENT 'Upper-case, trimmed spelling',
    ISO2 VARCHAR,
    _LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
) COMMENT = 'Non-ISO country spellings to ISO 3166-1 alpha-2 (generator reference table)';

-- DQ: the generator's answer key (Phase 9 compares detections with it).
CREATE TABLE IF NOT EXISTS VLP_DP.DQ.GENERATOR_RUNS (
    RUN_ID VARCHAR,
    MANIFEST VARIANT COMMENT 'run_manifest.json as written by the generator',
    _FILE_NAME VARCHAR,
    _LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
) COMMENT = 'One row per generator run (run_manifest.json)';

CREATE TABLE IF NOT EXISTS VLP_DP.DQ.ANOMALY_GROUND_TRUTH (
    RUN_ID VARCHAR,
    ANOMALY_ID VARCHAR,
    ANOMALY_TYPE VARCHAR,
    RULE_ID VARCHAR,
    DQ_DIMENSION VARCHAR,
    SOURCE VARCHAR,
    BUSINESS_KEY VARCHAR,
    COUNTRY VARCHAR,
    EVENT_DATE DATE,
    SCHEMA_ANOMALY BOOLEAN,
    ENTRY VARIANT COMMENT 'Full manifest line (related rules, details, landing locations)',
    _FILE_NAME VARCHAR,
    _FILE_ROW_NUMBER NUMBER(38,0),
    _LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
) COMMENT = 'Injected anomalies (anomaly_manifest.jsonl): the answer key';

CREATE TABLE IF NOT EXISTS VLP_DP.DQ.GENERATOR_RULE_VIOLATIONS (
    RUN_ID VARCHAR,
    RULE_ID VARCHAR,
    SOURCE VARCHAR,
    BUSINESS_KEY VARCHAR,
    MESSAGE VARCHAR,
    ENTRY VARIANT,
    _FILE_NAME VARCHAR,
    _FILE_ROW_NUMBER NUMBER(38,0),
    _LOADED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
) COMMENT = 'What the generator R1-R16 checker found (rule_violations.jsonl)';

GRANT USAGE ON FILE FORMAT VLP_DP.BRONZE.FF_REFERENCE_CSV TO ROLE VLP_LOADER;
GRANT USAGE ON FILE FORMAT VLP_DP.BRONZE.FF_GENERATOR_JSON TO ROLE VLP_LOADER;
GRANT SELECT ON TABLE VLP_DP.REF.FX_RATE_DAILY TO ROLE VLP_TRANSFORMER;
GRANT SELECT ON TABLE VLP_DP.REF.POSTAL_ZONE TO ROLE VLP_TRANSFORMER;
GRANT SELECT ON TABLE VLP_DP.REF.COUNTRY_ALIAS TO ROLE VLP_TRANSFORMER;
GRANT SELECT ON TABLE VLP_DP.DQ.GENERATOR_RUNS TO ROLE VLP_TRANSFORMER;
GRANT SELECT ON TABLE VLP_DP.DQ.ANOMALY_GROUND_TRUTH TO ROLE VLP_TRANSFORMER;
GRANT SELECT ON TABLE VLP_DP.DQ.GENERATOR_RULE_VIOLATIONS TO ROLE VLP_TRANSFORMER;
